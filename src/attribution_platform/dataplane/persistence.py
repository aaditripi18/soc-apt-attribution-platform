"""Typed, source-agnostic persistence operations for Observation and Evidence
(gate G0.8).

Connects the existing G0.3/G0.6 domain pipeline to Elasticsearch via the
:class:`~attribution_platform.dataplane.client.ElasticClient` abstraction —
this module never imports a specific client implementation, only the
Protocol. Four operations, deliberately the entire surface:
:func:`persist_observation`, :func:`load_observation`,
:func:`persist_evidence`, :func:`load_evidence`.

**No second schema.** The document body written to Elastic is exactly
:func:`attribution_platform.domain.to_serializable` applied to the domain
object — the same deterministic representation G0.3 already defined for
future persistence/API use (see that module's docstring). This module adds
no translation layer that reshapes field names or introduces new fields.

**Deserialization is new logic, scoped here, not in ``domain``.** G0.3 gave
the forward direction (``to_serializable``) but no inverse, because no gate
before this one needed to reconstruct a domain object from its serialized
form. The ``domain`` package must stay Elastic-agnostic and this reverse
mapping exists only because *this* layer promised a write-then-read round
trip — so it is implemented here, as the explicit, typed inverse of
``to_serializable`` for exactly the Observation/Evidence shapes, not as a
generic reflection-based deserializer and not as a new field on the domain
contracts themselves.

**G1.2 fix (round-trip completeness):** ``_derivation_provenance_from_dict``
originally omitted ``method_content_hash`` — the field serialized correctly
via ``to_serializable`` (nothing was ever lost from the *written* document)
but a *reloaded* ``Evidence`` silently came back with
``provenance.method_content_hash=None`` regardless of what was stored,
because the field simply wasn't read back out. No test exercised this gap
before G1.2's replay-through-persistence path (``derive_evidence`` from a
rule-pack-loaded ``DetectionResult`` is the first caller that ever produces
a non-``None`` ``method_content_hash`` and then persists it). Fixed
additively — the field is now read back exactly like every other optional
field here.

**Idempotency.** Every write uses the domain object's own id
(``observation_id`` / ``evidence_id``) as the Elasticsearch document id, so
persisting the same object twice performs the same upsert twice and leaves
identical end state — no separate dedup/idempotency-key mechanism is needed
(the ``ElasticClient.index_document`` contract requires this of every
implementation).

**Fail-closed.** A non-``Observation``/non-``Evidence`` input, a stored
document with a ``schema_version`` this gate does not recognize, a
missing/malformed field, or any underlying client failure all raise
:class:`~attribution_platform.dataplane.errors.ElasticIntegrationError` —
callers never receive a partially-built domain object.

Deliberately NOT here (forbidden this gate): detection rules, EQL/ES|QL
correlation, attack-chain logic, attribution scoring, candidate generation,
replay/bulk ingestion (G0.9), or the read-model API (G0.10). This module
persists and loads single domain objects one at a time; nothing more.
"""

