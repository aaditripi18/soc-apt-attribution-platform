@dataclass(frozen=True)
class PersistResult:
    """Where a domain object was written — the stage-1 provenance record
    (docs/architecture/03-system-data-flow.md) a later gate's provenance
    manifest will consume. Deliberately minimal: no Elastic response
    metadata (``_version``, ``result``, ...) is kept, since nothing yet
    needs it and the index/id pair is already fully deterministic (derived
    from the domain object's own id, not generated by Elastic)."""

    index: str
    document_id: str


def _wrap_client_error(exc: Exception, context: str) -> ElasticIntegrationError:
    if isinstance(exc, ElasticIntegrationError):
        return exc
    return ElasticIntegrationError(f"{context}: {exc}")


# ===========================================================================
# Observation
# ===========================================================================


def persist_observation(client: ElasticClient, observation: Observation) -> PersistResult:
    """Write ``observation`` to Elastic, keyed by its own ``observation_id``."""
    if not isinstance(observation, Observation):
        raise ElasticIntegrationError(
            f"persist_observation requires an Observation, got {type(observation).__name__}"
        )
    document = to_serializable(observation)
    try:
        client.ensure_index(OBSERVATIONS_INDEX, OBSERVATIONS_MAPPING)
        client.index_document(OBSERVATIONS_INDEX, observation.observation_id, document)
    except Exception as exc:  # noqa: BLE001 - re-raised as the one typed error below
        raise _wrap_client_error(
            exc, f"failed to persist Observation {observation.observation_id!r}"
        ) from exc
    return PersistResult(index=OBSERVATIONS_INDEX, document_id=observation.observation_id)


def load_observation(client: ElasticClient, observation_id: str) -> Observation | None:
    """Load the Observation stored under ``observation_id``, or ``None`` if absent."""
    try:
        doc = client.get_document(OBSERVATIONS_INDEX, observation_id)
    except Exception as exc:  # noqa: BLE001
        raise _wrap_client_error(exc, f"failed to load Observation {observation_id!r}") from exc
    if doc is None:
        return None
    return _observation_from_document(doc)


def _observation_from_document(doc: Mapping[str, Any]) -> Observation:
    try:
        schema_version = doc["schema_version"]
        if schema_version != OBSERVATION_SCHEMA_VERSION:
            raise ElasticIntegrationError(
                f"stored Observation schema_version {schema_version!r} does not match the "
                f"current {OBSERVATION_SCHEMA_VERSION!r} (schema migration not implemented "
                "at this gate)"
            )
        return Observation(
            observation_id=doc["observation_id"],
            timestamp=datetime.fromisoformat(doc["timestamp"]),
            raw_reference=_source_ref_from_dict(doc["raw_reference"]),
            timestamp_precision=(
                TimePrecision(doc["timestamp_precision"])
                if doc.get("timestamp_precision") is not None
                else None
            ),
            event=_event_metadata_from_dict(doc.get("event")),
            host=_host_ref_from_dict(doc.get("host")),
            user=_user_ref_from_dict(doc.get("user")),
            process=_process_ref_from_dict(doc.get("process")),
            network=_network_info_from_dict(doc.get("network")),
            file=_file_ref_from_dict(doc.get("file")),
            dll=_dll_ref_from_dict(doc.get("dll")),
            registry=_registry_ref_from_dict(doc.get("registry")),
            target_process=_process_ref_from_dict(doc.get("target_process")),
            process_access=_process_access_from_dict(doc.get("process_access")),
            remote_thread=_remote_thread_from_dict(doc.get("remote_thread")),
            dns=_dns_ref_from_dict(doc.get("dns")),
            file_stream=_file_stream_from_dict(doc.get("file_stream")),
            pipe=_pipe_ref_from_dict(doc.get("pipe")),
            wmi=_wmi_ref_from_dict(doc.get("wmi")),
            powershell=_powershell_ref_from_dict(doc.get("powershell")),
            target_user=_user_ref_from_dict(doc.get("target_user")),
            logon=_flat_ref_from_dict(LogonRef, _LOGON_FIELDS, doc.get("logon")),
            object_access=_flat_ref_from_dict(
                ObjectAccessRef, _OBJECT_ACCESS_FIELDS, doc.get("object_access")
            ),
            share=_flat_ref_from_dict(ShareRef, _SHARE_FIELDS, doc.get("share")),
            schema_version=schema_version,
        )
    except ElasticIntegrationError:
        raise
    except (KeyError, TypeError, ValueError, DomainContractError) as exc:
        raise ElasticIntegrationError(
            f"stored document could not be reconstructed into an Observation: {exc}"
        ) from exc


# ===========================================================================
# Evidence
# ===========================================================================


def persist_evidence(client: ElasticClient, evidence: Evidence) -> PersistResult:
    """Write ``evidence`` to Elastic, keyed by its own ``evidence_id``.

    ``attack_ref``, ``provenance`` (incl. ``source_observation_ids``), and
    all timestamps are part of ``to_serializable(evidence)`` and so are
    preserved verbatim — no separate handling is needed to keep them.
    """
    if not isinstance(evidence, Evidence):
        raise ElasticIntegrationError(
            f"persist_evidence requires an Evidence, got {type(evidence).__name__}"
        )
    document = to_serializable(evidence)
    try:
        client.ensure_index(EVIDENCE_INDEX, EVIDENCE_MAPPING)
        client.index_document(EVIDENCE_INDEX, evidence.evidence_id, document)
    except Exception as exc:  # noqa: BLE001
        raise _wrap_client_error(
            exc, f"failed to persist Evidence {evidence.evidence_id!r}"
        ) from exc
    return PersistResult(index=EVIDENCE_INDEX, document_id=evidence.evidence_id)


def load_evidence(client: ElasticClient, evidence_id: str) -> Evidence | None:
    """Load the Evidence stored under ``evidence_id``, or ``None`` if absent."""
    try:
        doc = client.get_document(EVIDENCE_INDEX, evidence_id)
    except Exception as exc:  # noqa: BLE001
        raise _wrap_client_error(exc, f"failed to load Evidence {evidence_id!r}") from exc
    if doc is None:
        return None
    return _evidence_from_document(doc)


def _evidence_from_document(doc: Mapping[str, Any]) -> Evidence:
    try:
        schema_version = doc["schema_version"]
        if schema_version != EVIDENCE_SCHEMA_VERSION:
            raise ElasticIntegrationError(
                f"stored Evidence schema_version {schema_version!r} does not match the "
                f"current {EVIDENCE_SCHEMA_VERSION!r} (schema migration not implemented "
                "at this gate)"
            )
        return Evidence(
            evidence_id=doc["evidence_id"],
            evidence_type=EvidenceType(doc["evidence_type"]),
            claim=doc["claim"],
            provenance=_derivation_provenance_from_dict(doc["provenance"]),
            attack_ref=_attack_ref_from_dict(doc.get("attack_ref")),
            quality=EvidenceQuality(doc["quality"]) if doc.get("quality") is not None else None,
            time_span=_time_span_from_dict(doc.get("time_span")),
            host=_host_ref_from_dict(doc.get("host")),
            user=_user_ref_from_dict(doc.get("user")),
            schema_version=schema_version,
        )
    except ElasticIntegrationError:
        raise
    except (KeyError, TypeError, ValueError, DomainContractError) as exc:
        raise ElasticIntegrationError(
            f"stored document could not be reconstructed into an Evidence: {exc}"
        ) from exc


# ===========================================================================
# Shared entity-group reconstruction (the explicit inverse of to_serializable
# for exactly the value types Observation/Evidence reference)
