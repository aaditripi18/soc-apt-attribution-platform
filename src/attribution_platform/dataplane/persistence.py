def _flat_ref_from_dict(cls: Any, fields: tuple[str, ...], d: Mapping[str, Any] | None) -> Any:
    """A flat all-optional entity group from its stored dict (None -> None)."""
    if d is None:
        return None
    return cls(**{f: d.get(f) for f in fields})


