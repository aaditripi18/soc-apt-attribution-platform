"""Deterministic diff between two vendored ATT&CK releases (doc 11 §G upgrade
step "KB-diff").

Answers, from the two bundles alone, what an upgrade changes for attribution:
which Groups, techniques (incl. sub-techniques), software and campaigns were
added, retired (became revoked/deprecated or disappeared) or modified; and, for
every Group active in both releases, which techniques entered or left its
active ``uses`` profile. Pure, read-only, sorted output; no network.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any

from attribution_platform.attack_knowledge.loader import AttackKnowledge, FrozenStixObject
from attribution_platform.attack_knowledge.traversal import (
    active_groups,
    is_active,
    techniques_used_by,
)

ATTACK_DIFF_VERSION = "attack-diff/1"

_KINDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("groups", ("intrusion-set",)),
    ("techniques", ("attack-pattern",)),
    ("software", ("malware", "tool")),
    ("campaigns", ("campaign",)),
)


def _external_id(obj: FrozenStixObject) -> str | None:
    for ref in obj.get("external_references") or ():
        if ref.get("source_name") == "mitre-attack" and ref.get("external_id"):
            return str(ref["external_id"])
    return None


def _label(obj: FrozenStixObject) -> dict[str, str]:
    return {"attack_id": _external_id(obj) or "", "name": str(obj.get("name", ""))}


def _active_by_id(knowledge: AttackKnowledge, types: Iterable[str]) -> dict[str, FrozenStixObject]:
    return {str(o["id"]): o for t in types for o in knowledge.objects_of_type(t) if is_active(o)}


def _sorted(items: Iterable[dict[str, str]]) -> list[dict[str, str]]:
    return sorted(items, key=lambda d: (d["attack_id"], d["name"]))


def diff_attack_versions(old: AttackKnowledge, new: AttackKnowledge) -> dict[str, Any]:
    """Diff ``old`` → ``new`` (JSON-ready dict)."""
    kinds: dict[str, Any] = {}
    for kind, types in _KINDS:
        before = _active_by_id(old, types)
        after = _active_by_id(new, types)
        added = [after[i] for i in after.keys() - before.keys()]
        retired = [before[i] for i in before.keys() - after.keys()]
        modified = [
            after[i]
            for i in after.keys() & before.keys()
            if after[i].get("modified") != before[i].get("modified")
        ]
        kinds[kind] = {
            "active_before": len(before),
            "active_after": len(after),
            "added": _sorted(_label(o) for o in added),
            "retired": _sorted(_label(o) for o in retired),
            "modified": _sorted(_label(o) for o in modified),
        }

    old_tech = _active_by_id(old, ("attack-pattern",))
    new_tech = _active_by_id(new, ("attack-pattern",))
    tech_label = {
        **{k: _label(v) for k, v in old_tech.items()},
        **{k: _label(v) for k, v in new_tech.items()},
    }
    old_groups = {str(g["id"]): g for g in active_groups(old)}
    profile_changes = []
    for group in active_groups(new):
        stix_id = str(group["id"])
        if stix_id not in old_groups:
            continue
        before_profile = set(techniques_used_by(old, stix_id))
        after_profile = set(techniques_used_by(new, stix_id))
        gained = after_profile - before_profile
        lost = before_profile - after_profile
        if gained or lost:
            profile_changes.append(
                {
                    **_label(group),
                    "profile_before": len(before_profile),
                    "profile_after": len(after_profile),
                    "techniques_added": _sorted(tech_label[t] for t in gained),
                    "techniques_removed": _sorted(tech_label[t] for t in lost),
                }
            )
    return {
        "diff_version": ATTACK_DIFF_VERSION,
        "from": {"attack_kb_version": old.attack_kb_version, "sha256": old.attack_kb_sha256},
        "to": {"attack_kb_version": new.attack_kb_version, "sha256": new.attack_kb_sha256},
        "kinds": kinds,
        "group_profile_changes": sorted(profile_changes, key=lambda d: (d["attack_id"], d["name"])),
    }


def render_attack_diff(diff: dict[str, Any]) -> str:
    """A short Markdown summary of :func:`diff_attack_versions` output."""
    lines = [
        f"# ATT&CK change report: `{diff['from']['attack_kb_version']}` → "
        f"`{diff['to']['attack_kb_version']}`",
        "",
        "_Generated by `scripts/diff_attack_versions.py` — do not edit by hand. "
        'Active objects only (revoked/deprecated excluded). "Modified" = the STIX '
        "`modified` timestamp changed, which includes metadata-only edits; the "
        "technique-profile table below is the attribution-relevant change._",
        "",
        "| Kind | Active before | Active after | Added | Retired | Modified |",
        "|---|---|---|---|---|---|",
    ]
    for kind, row in diff["kinds"].items():
        lines.append(
            f"| {kind} | {row['active_before']} | {row['active_after']} | {len(row['added'])} | "
            f"{len(row['retired'])} | {len(row['modified'])} |"
        )
    for kind in ("groups", "campaigns", "techniques"):
        for change in ("added", "retired"):
            items = diff["kinds"][kind][change]
            if items:
                lines += ["", f"## {kind.capitalize()} {change}", ""]
                lines += [f"- {i['attack_id']} {i['name']}" for i in items]
    changes = diff["group_profile_changes"]
    lines += [
        "",
        "## Group technique-profile changes",
        "",
        f"{len(changes)} Groups active in both releases changed their technique profile.",
        "",
        "| Group | Before | After | Added | Removed |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {c['attack_id']} {c['name']} | {c['profile_before']} | {c['profile_after']} | "
        f"{len(c['techniques_added'])} | {len(c['techniques_removed'])} |"
        for c in changes
    ]
    lines.append("")
    return "\n".join(lines)


__all__ = ["ATTACK_DIFF_VERSION", "diff_attack_versions", "render_attack_diff"]
