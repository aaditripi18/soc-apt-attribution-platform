"""Build (and optionally install) the Kibana dashboard of the platform's results
(ADR-0024).

The dashboard charts the two flat indices written by
``attribution_platform.api.kibana_export`` when an investigation is run with
``--elasticsearch``. This script writes its saved objects — two data views,
the visualisations and the dashboard — to ``kibana/attribution-dashboard.ndjson``
deterministically (fixed ids, sorted keys), so the tracked file can be
regenerated byte for byte.

    python scripts/build_kibana_dashboard.py              # write the file
    python scripts/build_kibana_dashboard.py --install    # and import it

``--install`` posts the file to Kibana's saved-objects import API at
``KIBANA_URL`` (default ``http://127.0.0.1:5601``) as ``ELASTIC_USERNAME``
(default ``elastic``) with ``ELASTIC_PASSWORD`` from the environment. The
objects can equally be imported by hand: Stack Management > Saved Objects >
Import.
"""

