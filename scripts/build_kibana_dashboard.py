def saved_objects() -> list[dict[str, Any]]:
    views = [
        {
            "type": "index-pattern",
            "id": view,
            "attributes": {"title": index, "name": name, "timeFieldName": "@timestamp"},
            "references": [],
        }
        for view, index, name in (
            (DETECTIONS_VIEW, DETECTIONS_INDEX, "Attribution platform: detections"),
            (MATCHES_VIEW, GROUP_MATCHES_INDEX, "Attribution platform: group matches"),
        )
    ]
    placed = visualizations()
    panels, references = [], []
    for position, (visualization, (x, y, w, h)) in enumerate(placed):
        # a stable id per panel, derived from the visualisation's own id
        index = str(uuid.uuid5(uuid.NAMESPACE_URL, f"attribution-panel:{visualization['id']}"))
        panels.append(
            {
                "version": "7.3.0",
                "type": "visualization",
                "gridData": {"x": x, "y": y, "w": w, "h": h, "i": index},
                "panelIndex": index,
                "embeddableConfig": {},
                "panelRefName": f"panel_{position}",
            }
        )
        references.append(
            {"name": f"panel_{position}", "type": "visualization", "id": visualization["id"]}
        )
    dashboard = {
        "type": "dashboard",
        "id": DASHBOARD_ID,
        "attributes": {
            "title": "APT Attribution Platform: detections and group matches",
            "description": (
                "ATT&CK techniques detected in the investigated logs and the threat groups "
                "whose public profile they resemble."
            ),
            "version": 1,
            "panelsJSON": _dumps(panels),
            "optionsJSON": _dumps({"useMargins": True, "hidePanelTitles": False}),
            "timeRestore": True,
            "timeFrom": "now-15y",
            "timeTo": "now",
            "kibanaSavedObjectMeta": {
                "searchSourceJSON": _dumps(
                    {"query": {"query": "", "language": "kuery"}, "filter": []}
                )
            },
        },
        "references": references,
    }
    return [*views, *(v for v, _ in placed), dashboard]


def render() -> str:
    return "".join(_dumps(obj) + "\n" for obj in saved_objects())


def install(text: str, env: dict[str, str]) -> int:
    password = env.get("ELASTIC_PASSWORD")
    if not password:
        print("ELASTIC_PASSWORD must be set to install the dashboard.", file=sys.stderr)
        return 1
    base = env.get("KIBANA_URL", "http://127.0.0.1:5601").rstrip("/")
    user = env.get("ELASTIC_USERNAME", "elastic")
    boundary = "attribution-dashboard-boundary"
    body = (
        f"--{boundary}\r\n"
        'Content-Disposition: form-data; name="file"; filename="attribution-dashboard.ndjson"\r\n'
        "Content-Type: application/ndjson\r\n\r\n"
        f"{text}\r\n--{boundary}--\r\n"
    ).encode()
    token = base64.b64encode(f"{user}:{password}".encode()).decode()
    request = urllib.request.Request(  # noqa: S310 - the operator's own Kibana
        f"{base}/api/saved_objects/_import?overwrite=true",
        data=body,
        headers={
            "kbn-xsrf": "true",
            "Authorization": f"Basic {token}",
            "Content-Type": f"multipart/form-data; boundary={boundary}",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
            result = json.loads(response.read())
    except urllib.error.HTTPError as exc:
        print(f"Kibana refused the import: HTTP {exc.code}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"Kibana could not be reached at {base}: {exc}", file=sys.stderr)
        return 1
    if not result.get("success"):
        for error in result.get("errors", []):
            print(f"not imported: {error.get('type')} {error.get('id')}: {error.get('error')}")
        return 1
    print(f"Imported {result.get('successCount')} objects.")
    print(f"Dashboard: {base}/app/dashboards#/view/{DASHBOARD_ID}")
    return 0


def main(argv: list[str]) -> int:
    text = render()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} ({len(saved_objects())} objects)")
    return install(text, dict(os.environ)) if "--install" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
