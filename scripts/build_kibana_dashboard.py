def _dumps(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def _count(label: str) -> dict[str, Any]:
    return {
        "id": "1",
        "enabled": True,
        "type": "count",
        "schema": "metric",
        "params": {"customLabel": label},
    }


def _metric(agg: str, field: str, label: str, agg_id: str = "1") -> dict[str, Any]:
    return {
        "id": agg_id,
        "enabled": True,
        "type": agg,
        "schema": "metric",
        "params": {"field": field, "customLabel": label},
    }


def _terms(
    agg_id: str, field: str, label: str, size: int, schema: str, order_by: str = "1"
) -> dict[str, Any]:
    return {
        "id": agg_id,
        "enabled": True,
        "type": "terms",
        "schema": schema,
        "params": {
            "field": field,
            "orderBy": order_by,
            "order": "desc",
            "size": size,
            "otherBucket": False,
            "missingBucket": False,
            "customLabel": label,
        },
    }


def _visualization(
    name: str,
    title: str,
    kind: str,
    params: dict[str, Any],
    aggs: list[dict[str, Any]],
    view: str | None,
    query: str = "",
) -> dict[str, Any]:
    source: dict[str, Any] = {"query": {"query": query, "language": "kuery"}, "filter": []}
    references = []
    if view is not None:
        source["indexRefName"] = _INDEX_REF
        references.append({"name": _INDEX_REF, "type": "index-pattern", "id": view})
    return {
        "type": "visualization",
        "id": f"attribution-{name}",
        "attributes": {
            "title": title,
            "description": "",
            "version": 1,
            "uiStateJSON": "{}",
            "visState": _dumps({"title": title, "type": kind, "params": params, "aggs": aggs}),
            "kibanaSavedObjectMeta": {"searchSourceJSON": _dumps(source)},
        },
        "references": references,
    }


